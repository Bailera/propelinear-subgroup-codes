#!/usr/bin/env python3
"""
exact_fq.py -- Exact propelinear optimum at (n,4,2) over F_q, q prime, by
exhaustive enumeration, and independent verification of a code over F_q.

Over F_q the ambient group is

    U_n^(q) = F_q^n x| Gamma_n^(q),    Gamma_n^(q) = F_q^* wr S_n,

the monomial group of F_q-linear isometries of the Hamming space; for q = 2 it
is S_n and U_n^(2) = U_n. A monomial map M is stored as a pair (p, s): a
permutation p in one-line notation (p[i] is the image of i, indexed from 0)
and a tuple s of nonzero scalars. It acts by

    (M v)[p[i]] = s[i] * v[i]   (mod q),

which for s = (1, ..., 1) is the action of the binary case, w[p[i]] = v[i].
The product is (x, M)(y, N) = (x + M y, M N). The propelinear distance is
taken with logarithms to base q, so two codewords of order q^2 are at
distance 4 exactly when they meet only in the identity.

A group of order q^2 is abelian, so a subgroup of that order is either cyclic,
generated by an element of order q^2, or elementary abelian, generated by two
commuting elements of order q. As in exact_k2.py for q = 2, all of them can be
listed. The largest family of nondegenerate ones meeting pairwise only in the
identity is then found by an ILP solved by CBC, with one constraint for each
nonidentity element lying in at least two candidates.

    python exact_fq.py --n 4 --q 3
    python exact_fq.py --n 4 --q 2        # check: reproduces A^P(4,4,2) = 24
    python exact_fq.py --verify clique_442_q3.json --n 4 --q 3

A run writes clique_<n>42_q<q>.json and results_<n>42_q<q>.json. In the clique
file each codeword is the list of its q^2 elements, and each element is a
triple [vector, permutation, scalars] in the format above.

--force-linear requires at least one linear codeword in the family and
--forbid-linear excludes them; the output files then carry the suffix
_forcelin or _nolin. At (4,4,2) over F_3 both runs reach the optimum 28,
whereas over F_2 at n = 4 requiring a linear codeword lowers it from 24 to 22.

--verify checks a clique file independently of the enumeration code: it
rebuilds the operation from explicit monomial matrices, checks that it is
associative, and tests that every codeword is a nondegenerate subgroup of
order q^2 and that any two codewords meet only in the identity.

The enumeration is meant for n = 4. The group has q^n (q-1)^n n! elements, and
n = 5 with q = 3 is already slow.
"""
import argparse
import itertools
import json
import random
import time
from collections import defaultdict

ap = argparse.ArgumentParser()
ap.add_argument("--n", type=int, required=True)
ap.add_argument("--q", type=int, required=True, help="a prime")
ap.add_argument("--time-limit", type=int, default=3600)
lin_opt = ap.add_mutually_exclusive_group()
lin_opt.add_argument("--force-linear", action="store_true",
                     help="require at least one linear codeword")
lin_opt.add_argument("--forbid-linear", action="store_true",
                     help="exclude every linear codeword")
ap.add_argument("--verify", metavar="CLIQUE",
                help="verify this clique file instead of computing one")
a = ap.parse_args()
n, q = a.n, a.q
if q < 2 or any(q % r == 0 for r in range(2, int(q ** 0.5) + 1)):
    raise SystemExit("q must be a prime")


# --------------------------------------------------------------- verification
def verify(path):
    """Check a clique file from first principles, with explicit matrices."""
    with open(path) as fh:
        data = json.load(fh)

    def matrix(p, s):
        if sorted(p) != list(range(n)) or len(s) != n or any(not 1 <= c < q for c in s):
            raise SystemExit(f"ABORTED: not a monomial map: {p}, {s}")
        M = [[0] * n for _ in range(n)]
        for i in range(n):
            M[p[i]][i] = s[i]
        return tuple(tuple(row) for row in M)

    def mat_mul(A, B):
        return tuple(tuple(sum(A[i][l] * B[l][j] for l in range(n)) % q
                           for j in range(n)) for i in range(n))

    def mat_vec(A, v):
        return tuple(sum(A[i][l] * v[l] for l in range(n)) % q for i in range(n))

    def prod(g, h):
        (x, A), (y, B) = g, h
        Ay = mat_vec(A, y)
        return (tuple((x[i] + Ay[i]) % q for i in range(n)), mat_mul(A, B))

    ident = (tuple([0] * n), matrix(list(range(n)), [1] * n))

    rng = random.Random(12345)

    def rnd():
        p = list(range(n))
        rng.shuffle(p)
        return (tuple(rng.randrange(q) for _ in range(n)),
                matrix(p, [rng.randrange(1, q) for _ in range(n)]))

    bad = sum(prod(prod(g, h), k) != prod(g, prod(h, k))
              for g, h, k in ((rnd(), rnd(), rnd()) for _ in range(2000)))
    if bad:
        raise SystemExit(f"ABORTED: the operation is not associative ({bad}/2000)")

    code = []
    for cw in data:
        elems = []
        for x, p, s in cw:
            if len(x) != n or any(not 0 <= c < q for c in x):
                raise SystemExit(f"ABORTED: not a vector of F_{q}^{n}: {x}")
            elems.append((tuple(x), matrix(p, s)))
        code.append(frozenset(elems))

    def order(g):
        k, h = 1, g
        while h != ident:
            h, k = prod(h, g), k + 1
        return k

    checks = {
        f"order {q * q}": all(len(C) == q * q for C in code),
        "contains the identity": all(ident in C for C in code),
        "nondegenerate": all(len({x for x, M in C}) == len(C) for C in code),
        "closed under product": all(prod(g, h) in C for C in code for g in C for h in C),
        "pairwise only in e": all(len(C & D) == 1 for C, D in itertools.combinations(code, 2)),
    }
    print(f"\n[verify] {path}: {len(code)} codewords in U_{n}^({q})")
    for name, ok in checks.items():
        print(f"    {name:.<26} {'OK' if ok else 'FAIL'}")
    print(f"    linear codewords ......... {sum(all(M == ident[1] for x, M in C) for C in code)}")
    print(f"    cyclic codewords ......... {sum(any(order(g) == q * q for g in C) for C in code)}")
    ok = all(checks.values())
    print(f"    {'VERIFIED' if ok else 'FAILED'}")
    return ok


if a.verify:
    raise SystemExit(0 if verify(a.verify) else 1)


# ---------------------------------------------------------------- the group
t0 = time.time()
mons = [(p, s) for p in itertools.permutations(range(n))
        for s in itertools.product(range(1, q), repeat=n)]
mon_id = {m: i for i, m in enumerate(mons)}
vecs = list(itertools.product(range(q), repeat=n))
vec_id = {v: i for i, v in enumerate(vecs)}
NM, NV = len(mons), len(vecs)


def mon_mul(A, B):
    (pa, sa), (pb, sb) = A, B
    return (tuple(pa[pb[i]] for i in range(n)),
            tuple(sa[pb[i]] * sb[i] % q for i in range(n)))


def mon_act(A, v):
    p, s = A
    w = [0] * n
    for i in range(n):
        w[p[i]] = s[i] * v[i] % q
    return tuple(w)


mulM = [[mon_id[mon_mul(A, B)] for B in mons] for A in mons]
act = [[vec_id[mon_act(A, v)] for v in vecs] for A in mons]
addV = [[vec_id[tuple((s + t) % q for s, t in zip(u, v))] for v in vecs] for u in vecs]
N = NM * NV
I_M = mon_id[(tuple(range(n)), tuple([1] * n))]
E = I_M * NV + vec_id[tuple([0] * n)]


def mul(g, h):
    m1, x = divmod(g, NV)
    m2, y = divmod(h, NV)
    return mulM[m1][m2] * NV + addV[x][act[m1][y]]


def powers(g):
    out, h = [E], g
    while h != E:
        out.append(h)
        h = mul(h, g)
    return out


print(f"|U_{n}^({q})| = {N}")
order = [len(powers(g)) for g in range(N)]
o1 = [g for g in range(N) if order[g] == q]
o2 = [g for g in range(N) if order[g] == q * q]
print(f"  elements of order {q}: {len(o1)} | of order {q * q}: {len(o2)}  ({time.time()-t0:.0f}s)")

# --------------------------------------------------- subgroups of order q^2
subs = {frozenset(powers(g)) for g in o2}
n_cyclic = len(subs)
for i, x in enumerate(o1):
    X = powers(x)
    Xs = set(X)
    for y in o1[i + 1:]:
        if y in Xs or mul(x, y) != mul(y, x):
            continue
        subs.add(frozenset(mul(u, v) for u in X for v in powers(y)))
nd = sorted((H for H in subs if len({g % NV for g in H}) == q * q), key=sorted)
is_lin = [all(g // NV == I_M for g in H) for H in nd]
print(f"  subgroups of order {q * q}: {len(subs)} ({n_cyclic} cyclic) | "
      f"nondegenerate: {len(nd)} | linear: {sum(is_lin)}  ({time.time()-t0:.0f}s)")

# ----------------------------------------------------------------------- ILP
import pulp

owners = defaultdict(list)
for j, H in enumerate(nd):
    for g in H:
        if g != E:
            owners[g].append(j)
prob = pulp.LpProblem("fq", pulp.LpMaximize)
xv = [pulp.LpVariable(f"x{j}", cat="Binary") for j in range(len(nd))]
prob += pulp.lpSum(xv)
rows = 0
for js in owners.values():
    if len(js) >= 2:
        prob += pulp.lpSum(xv[j] for j in js) <= 1
        rows += 1
lin_idx = [j for j in range(len(nd)) if is_lin[j]]
restriction = ("at least one linear codeword" if a.force_linear else
               "no linear codeword" if a.forbid_linear else None)
if a.force_linear:
    prob += pulp.lpSum(xv[j] for j in lin_idx) >= 1
if a.forbid_linear:
    for j in lin_idx:
        prob += xv[j] == 0
print(f"\n  {rows} constraints, solving ILP (limit {a.time_limit}s)"
      + (f", restriction: {restriction}" if restriction else "") + "...")
t1 = time.time()
prob.solve(pulp.PULP_CBC_CMD(msg=False, timeLimit=a.time_limit))
status = pulp.LpStatus[prob.status]
# PuLP reports "Optimal" also when CBC stops on the time limit with a
# feasible solution; only sol_status tells a proven optimum apart.
if status == "Optimal" and prob.sol_status != pulp.LpSolutionOptimal:
    status = "Feasible (time limit, not proven optimal)"
exact = status == "Optimal"
sel = [j for j in range(len(nd)) if pulp.value(xv[j]) and pulp.value(xv[j]) > 0.5]
value = len(sel)
aq = (q ** n - 1) // (q ** 2 - 1) if n % 2 == 0 else None
head = f"({n},4,2) over F_{q}" + (f", with {restriction}" if restriction else "")
print(f"\n===== {head}: {value} codewords  [CBC {status}]  ({time.time()-t1:.0f}s) =====")
print(f"  {'EXACT VALUE' if exact else 'lower bound (ILP did not prove optimality)'}")
if aq is not None:
    print(f"  against A_{q}({n},4,2) = {aq}, the size of a spread: factor {value / aq:.2f}")

# ------------------------------------------------------------------- output


def element(g):
    m, v = divmod(g, NV)
    p, s = mons[m]
    return [list(vecs[v]), list(p), list(s)]


tag = (f"{n}42_q{q}" + ("_forcelin" if a.force_linear else "")
       + ("_nolin" if a.forbid_linear else ""))
clique = [sorted(element(g) for g in nd[j]) for j in sel]
with open(f"clique_{tag}.json", "w") as fh:
    json.dump(clique, fh)
ok = verify(f"clique_{tag}.json")
with open(f"results_{tag}.json", "w") as fh:
    json.dump({"case": f"({n},4,2) over F_{q}", "A_P": value, "status": status,
               "exact": exact, "restriction": restriction, "A_q": aq,
               "group_order": N, "subgroups_of_order_q2": len(subs),
               "cyclic_subgroups": n_cyclic, "nondegenerate": len(nd),
               "linear_candidates": sum(is_lin),
               "linear_in_clique": sum(is_lin[j] for j in sel),
               "verified": ok}, fh, indent=2)
print(f"  written: results_{tag}.json, clique_{tag}.json")
if not ok:
    raise SystemExit(1)
